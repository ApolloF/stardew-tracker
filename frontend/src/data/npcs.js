const SEASON_ORDER = { Spring: 0, Summer: 1, Fall: 2, Winter: 3 };

// Days until birthday from current position
export function daysUntilBirthday(npc, currentSeason, currentDay, currentYear) {
  const curSeasonIdx = SEASON_ORDER[currentSeason];
  const npcSeasonIdx = SEASON_ORDER[npc.season];

  // Days elapsed in current year
  const curAbsolute = curSeasonIdx * 28 + currentDay;
  const npcAbsolute = npcSeasonIdx * 28 + npc.day;

  if (npcAbsolute > curAbsolute) return npcAbsolute - curAbsolute;
  if (npcAbsolute === curAbsolute) return 0; // today!
  // Wraps to next year
  return (4 * 28) - curAbsolute + npcAbsolute;
}

// Get upcoming birthdays sorted by days away
export function getUpcomingBirthdays(currentSeason, currentDay, currentYear, limit = 32) {
  return NPCS
    .map(npc => ({ ...npc, daysAway: daysUntilBirthday(npc, currentSeason, currentDay, currentYear) }))
    .sort((a, b) => a.daysAway - b.daysAway)
    .slice(0, limit);
}
